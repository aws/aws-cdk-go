type FlowEntitlementProps struct {
	// A description of the entitlement.
	//
	// This description appears only on the MediaConnect console
	// and is not visible outside of the current AWS account.
	// Experimental.
	Description *string `field:"required" json:"description" yaml:"description"`
	// The flow to set the entitlement from.
	// Experimental.
	Flow IFlow `field:"required" json:"flow" yaml:"flow"`
	// The AWS account IDs that you want to share your content with.
	//
	// The receiving accounts (subscribers)
	// will be allowed to create their own flows using your content as the source.
	// Experimental.
	Subscribers *[]*string `field:"required" json:"subscribers" yaml:"subscribers"`
	// The percentage of the entitlement data transfer fee that you want the subscriber to be responsible for.
	// Default: - the MediaConnect service default.
	//
	// Experimental.
	DataTransferSubscriberFeePercent *float64 `field:"optional" json:"dataTransferSubscriberFeePercent" yaml:"dataTransferSubscriberFeePercent"`
	// Options for encrypting the entitlement.
	//
	// Only static key encryption is supported for entitlements.
	// Default: - no encryption.
	//
	// Experimental.
	Encryption *StaticKeyEncryption `field:"optional" json:"encryption" yaml:"encryption"`
	// An indication of whether the new entitlement should be enabled or disabled as soon as it is created.
	// Default: - undefined; when omitted, MediaConnect enables the entitlement (ENABLED) at deploy time.
	//
	// Experimental.
	EntitlementStatus EntitlementStatus `field:"optional" json:"entitlementStatus" yaml:"entitlementStatus"`
	// The name of the entitlement.
	//
	// This value must be unique within the current flow.
	// Default: autogenerated.
	//
	// Experimental.
	FlowEntitlementName *string `field:"optional" json:"flowEntitlementName" yaml:"flowEntitlementName"`
}

