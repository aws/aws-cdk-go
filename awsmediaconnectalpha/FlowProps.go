type FlowProps struct {
	// The settings for the source that you want to use for the new flow.
	// Experimental.
	Source SourceConfiguration `field:"required" json:"source" yaml:"source"`
	// The Availability Zone that you want to create the flow in.
	//
	// These options are limited to the Availability Zones within the current AWS Region.
	// Default: - chosen by MediaConnect.
	//
	// Experimental.
	AvailabilityZone *string `field:"optional" json:"availabilityZone" yaml:"availabilityZone"`
	// Encoding configuration applied to the NDI source when transcoding it to a transport stream for downstream distribution.
	//
	// Required when the flow source uses the NDI SpeedHQ protocol
	// (see {@link SourceConfiguration.ndi}).
	// Default: - no encoding config; required for NDI sources.
	//
	// Experimental.
	EncodingConfig *EncodingConfig `field:"optional" json:"encodingConfig" yaml:"encodingConfig"`
	// The name of the flow.
	// Default: - autogenerated.
	//
	// Experimental.
	FlowName *string `field:"optional" json:"flowName" yaml:"flowName"`
	// Determines the processing capacity and feature set of the flow.
	//
	// Set this optional parameter to LARGE if you want to enable NDI outputs on the flow.
	// Default: - undefined; when omitted, MediaConnect applies FlowSize.MEDIUM at deploy time
	//
	// Experimental.
	FlowSize FlowSize `field:"optional" json:"flowSize" yaml:"flowSize"`
	// The maintenance window for the flow.
	// Default: - chosen by MediaConnect.
	//
	// Experimental.
	MaintenanceConfiguration *MaintenanceWindow `field:"optional" json:"maintenanceConfiguration" yaml:"maintenanceConfiguration"`
	// The media streams that are associated with the flow.
	//
	// After you associate a media stream with a source, you can also associate it with outputs on the flow.
	// Default: No Media Streams.
	//
	// Experimental.
	MediaStreams *[]MediaStream `field:"optional" json:"mediaStreams" yaml:"mediaStreams"`
	// Specifies the configuration settings for a flow's NDI source or output.
	//
	// Required when the flow includes an NDI source or output.
	// Default: No NDI Configuration applied.
	//
	// Experimental.
	NdiConfig *NdiConfig `field:"optional" json:"ndiConfig" yaml:"ndiConfig"`
	// The settings for source failover.
	// Default: No source failover configuration applied.
	//
	// Experimental.
	SourceFailoverConfig FailoverConfig `field:"optional" json:"sourceFailoverConfig" yaml:"sourceFailoverConfig"`
	// The settings for source monitoring.
	// Default: No source monitoring configuration applied.
	//
	// Experimental.
	SourceMonitoringConfig *SourceMonitoringConfig `field:"optional" json:"sourceMonitoringConfig" yaml:"sourceMonitoringConfig"`
	// The VPC Interfaces for this flow.
	// Default: No VPC Interface configuration applied.
	//
	// Experimental.
	VpcInterfaces *[]*VpcInterfaceConfig `field:"optional" json:"vpcInterfaces" yaml:"vpcInterfaces"`
}

